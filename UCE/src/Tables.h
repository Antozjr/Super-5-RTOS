#include <Arduino.h>

/**
 * Busca el índice inferior en un eje ordenado.
 */
static inline uint8_t tableAxisIndex(const uint16_t* axis, uint16_t value) {
    for (uint8_t i = 0; i < TABLE_SIZE - 1; i++) {
        if (value <= axis[i + 1]) return i;
    }
    return TABLE_SIZE - 2;
}

/**
 * Interpolación bilineal sobre tabla uint8_t.
 * @return Valor interpolado (misma escala que la tabla)
 */
static inline float tableLookup_u8(const uint8_t tbl[TABLE_SIZE][TABLE_SIZE],
                                   uint16_t rpm, uint16_t map_kpa10) {
    uint8_t xi = tableAxisIndex(TABLE_RPM_AXIS, rpm);
    uint8_t yi = tableAxisIndex(TABLE_MAP_AXIS, map_kpa10 / 10);

    float xf = (float)(rpm - TABLE_RPM_AXIS[xi]) /
               (TABLE_RPM_AXIS[xi+1] - TABLE_RPM_AXIS[xi]);
    float yf = (float)(map_kpa10/10 - TABLE_MAP_AXIS[yi]) /
               (TABLE_MAP_AXIS[yi+1] - TABLE_MAP_AXIS[yi]);

    float v00 = tbl[yi][xi];
    float v10 = tbl[yi][xi+1];
    float v01 = tbl[yi+1][xi];
    float v11 = tbl[yi+1][xi+1];

    return v00*(1-xf)*(1-yf) + v10*xf*(1-yf) + v01*(1-xf)*yf + v11*xf*yf;
}

/**
 * Interpolación bilineal sobre tabla int8_t (ignición).
 */
static inline float tableLookup_i8(const int8_t tbl[TABLE_SIZE][TABLE_SIZE],
                                   uint16_t rpm, uint16_t map_kpa10) {
    uint8_t xi = tableAxisIndex(TABLE_RPM_AXIS, rpm);
    uint8_t yi = tableAxisIndex(TABLE_MAP_AXIS, map_kpa10 / 10);

    float xf = (float)(rpm - TABLE_RPM_AXIS[xi]) /
               (TABLE_RPM_AXIS[xi+1] - TABLE_RPM_AXIS[xi]);
    float yf = (float)(map_kpa10/10 - TABLE_MAP_AXIS[yi]) /
               (TABLE_MAP_AXIS[yi+1] - TABLE_MAP_AXIS[yi]);

    float v00 = tbl[yi][xi];
    float v10 = tbl[yi][xi+1];
    float v01 = tbl[yi+1][xi];
    float v11 = tbl[yi+1][xi+1];

    return v00*(1-xf)*(1-yf) + v10*xf*(1-yf) + v01*(1-xf)*yf + v11*xf*yf;
}

